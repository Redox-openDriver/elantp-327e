pub const HELD: [Key; 4] = [Key::Ctrl, Key::Shift, Key::Alt, Key::Super];

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    #[test]
    fn every_key_has_its_own_linux_code() {
        let codes: BTreeSet<u16> = Key::ALL.iter().map(|key| code(*key)).collect();
        assert_eq!(codes.len(), Key::ALL.len());
        assert_eq!((code(Key::A), code(Key::Enter), code(Key::VolumeUp), code(Key::Super)), (30, 28, 115, 125));
        assert!(codes.iter().all(|code| (1..0x2ff).contains(code)));
    }
}
